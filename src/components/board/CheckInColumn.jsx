import { Link } from 'react-router-dom';
import { ArrowRight, CheckCircle2, Circle, Flame, Loader2, RotateCcw } from 'lucide-react';
import { BRAND, CURSOR, cursorKey } from './boardConfig';
import ProfileStrip from './ProfileStrip';
import { dayLabel } from './checkInConfig';

const SOURCE_LABEL = {
  season: 'Season',
  development: 'Development',
  business: 'Business',
  recruiting: 'Recruiting',
  identity: 'Identity',
};

const card = {
  background: '#FFFFFF',
  border: '1px solid rgba(30,58,90,0.12)',
};

function SectionHeading({ children, note }) {
  return (
    <div className="mb-2 flex items-baseline justify-between gap-2">
      <span
        className="text-[8px] font-bold uppercase tracking-[0.24em]"
        style={{ color: 'rgba(30,58,90,0.5)' }}
      >
        {children}
      </span>
      {note ? (
        <span className="text-[8px] font-bold uppercase tracking-[0.18em]" style={{ color: BRAND.copper }}>
          {note}
        </span>
      ) : null}
    </div>
  );
}

// The Check-in column: onboarding while it is owed, and the daily loop after
// that. Every task on it is generated by another column — the check-off is the
// Fellow's side of the loop, and it resets with the day.
export default function CheckInColumn({ column, checkIn, user, selectedKey }) {
  const enabled = Boolean(user);
  const { tasks, onboarding, handled, total, streak, loading, failed, retry, busyKey, toggle } = checkIn;
  const outstanding = tasks.filter((task) => !task.handled).length;
  const openSteps = onboarding.filter((step) => !step.done);
  const Icon = column.icon;

  return (
    <section
      data-hh-module={column.label}
      data-hh-scroll
      className="flex w-[86%] shrink-0 snap-start flex-col overflow-y-auto scrollbar-hide pb-2 md:w-auto md:shrink md:overflow-visible"
    >
      <header className="mb-2.5 shrink-0 border-t-2 pt-2" style={{ borderColor: BRAND.copper }}>
        <div className="flex items-center gap-1.5">
          <Icon className="h-3.5 w-3.5 shrink-0" style={{ color: BRAND.copper }} />
          <span
            className="text-[8px] font-bold uppercase tracking-[0.3em]"
            style={{ color: 'rgba(30,58,90,0.45)' }}
          >
            {column.index}
          </span>
          <h2
            className="min-w-0 flex-1 truncate text-[12px] font-bold uppercase tracking-[0.16em]"
            style={{ color: BRAND.navy }}
          >
            {column.label}
          </h2>
        </div>
        <p className="mt-1 text-[10px] leading-snug" style={{ color: 'rgba(26,26,26,0.6)' }}>
          {column.tagline}
        </p>
      </header>

      {failed ? (
        <div className="rounded-[10px] p-3 text-center" style={card}>
          <p className="text-[11px] leading-snug" style={{ color: BRAND.navy }}>
            The loop could not be read. Nothing is lost.
          </p>
          <button
            type="button"
            onClick={retry}
            className="mt-2 inline-flex items-center gap-1.5 rounded-full px-3 py-1.5 text-[8px] font-bold uppercase tracking-[0.2em]"
            style={{ background: BRAND.navy, color: BRAND.cream }}
          >
            <RotateCcw className="h-3 w-3" /> Read again
          </button>
        </div>
      ) : loading ? (
        <div className="flex items-center gap-2 rounded-[10px] px-3 py-2.5" style={card}>
          <Loader2 className="h-3.5 w-3.5 animate-spin" style={{ color: BRAND.copper }} />
          <span
            className="text-[8px] font-bold uppercase tracking-[0.22em]"
            style={{ color: BRAND.copper }}
          >
            Reading your loop
          </span>
        </div>
      ) : (
        <>
          <ProfileStrip profile={checkIn.profile} />

          <div className="mt-2.5 rounded-[10px] px-3 py-3" style={card}>
            <div className="flex items-baseline justify-between gap-2">
              <span
                className="text-[9px] font-bold uppercase tracking-[0.2em]"
                style={{ color: BRAND.navy }}
              >
                {handled} of {total} handled
              </span>
              <span
                className="inline-flex items-center gap-1 text-[8px] font-bold uppercase tracking-[0.16em]"
                style={{ color: streak > 0 ? BRAND.copper : 'rgba(30,58,90,0.5)' }}
              >
                <Flame className="h-3 w-3" />
                {streak > 0 ? `${streak}-day streak` : 'No streak yet'}
              </span>
            </div>

            <div
              className="mt-2 h-[4px] w-full overflow-hidden rounded-full"
              style={{ background: 'rgba(30,58,90,0.10)' }}
            >
              <div
                className="h-full rounded-full transition-[width] duration-500"
                style={{
                  width: total ? `${(handled / total) * 100}%` : '0%',
                  background: `linear-gradient(90deg, ${BRAND.navy}, ${BRAND.gold})`,
                }}
              />
            </div>

            <p className="mt-2 text-[9px] font-bold uppercase tracking-[0.16em]" style={{ color: 'rgba(30,58,90,0.5)' }}>
              {dayLabel()}
              {outstanding === 0 ? ' · settled' : ` · ${outstanding} outstanding`}
            </p>
          </div>

          <div className="mt-3">
            <SectionHeading>Today</SectionHeading>
            <div className="space-y-2">
              {tasks.length === 0 ? (
                <div className="rounded-[10px] p-3" style={card}>
                  <p className="text-[11px] leading-snug" style={{ color: BRAND.navy }}>
                    Nothing outstanding. Turn to a column and start something.
                  </p>
                </div>
              ) : (
                tasks.map((task) => (
                  <div
                    key={task.key}
                    data-hh-card={cursorKey.task(task.key)}
                    className="flex items-start gap-2 rounded-[10px] p-2.5"
                    style={selectedKey === cursorKey.task(task.key) ? { ...card, ...CURSOR } : card}
                  >
                    <button
                      type="button"
                      disabled={!enabled || busyKey === task.key}
                      onClick={() => toggle(task)}
                      aria-pressed={task.handled}
                      aria-label={`${task.handled ? 'Reopen' : 'Mark handled'}: ${task.title}`}
                      className="mt-[1px] shrink-0 disabled:opacity-40"
                      style={{ color: task.handled ? BRAND.copper : 'rgba(30,58,90,0.35)' }}
                    >
                      {task.handled ? (
                        <CheckCircle2 className="h-4 w-4" />
                      ) : (
                        <Circle className="h-4 w-4" />
                      )}
                    </button>

                    <Link to={task.to} className="group min-w-0 flex-1">
                      <span
                        className="block text-[11px] font-bold leading-snug"
                        style={{
                          color: task.handled ? 'rgba(30,58,90,0.45)' : BRAND.navy,
                          textDecoration: task.handled ? 'line-through' : 'none',
                        }}
                      >
                        {task.title}
                      </span>
                      <span
                        className="mt-0.5 block text-[10px] leading-snug"
                        style={{ color: 'rgba(26,26,26,0.62)' }}
                      >
                        {task.meta}
                      </span>
                      <span
                        className="mt-1 flex items-center gap-1 text-[7.5px] font-bold uppercase tracking-[0.2em]"
                        style={{ color: BRAND.copper }}
                      >
                        {SOURCE_LABEL[task.column] || 'Dashboard'}
                        <ArrowRight className="h-[9px] w-[9px] transition-transform group-hover:translate-x-0.5" />
                      </span>
                    </Link>
                  </div>
                ))
              )}
            </div>

            {!enabled ? (
              <p className="mt-2 text-[9px] leading-snug" style={{ color: 'rgba(30,58,90,0.55)' }}>
                A check-in belongs to a Fellow. Sign in to start one.
              </p>
            ) : null}
          </div>

          <div className="mt-3">
            <SectionHeading note={openSteps.length ? `${openSteps.length} left` : null}>
              Onboarding
            </SectionHeading>

            {openSteps.length === 0 ? (
              <div className="rounded-[10px] p-3" style={card}>
                <p className="text-[11px] leading-snug" style={{ color: BRAND.navy }}>
                  Onboarding is complete. The dashboard is yours.
                </p>
              </div>
            ) : (
              <div className="space-y-2">
                {openSteps.map((step) => (
                  <Link
                    key={step.key}
                    to={step.to}
                    data-hh-card={cursorKey.step(step.key)}
                    className="group flex items-start gap-2 rounded-[10px] p-2.5"
                    style={selectedKey === cursorKey.step(step.key) ? { ...card, ...CURSOR } : card}
                  >
                    <Circle className="mt-[1px] h-4 w-4 shrink-0" style={{ color: 'rgba(30,58,90,0.35)' }} />
                    <span className="min-w-0 flex-1">
                      <span className="block text-[11px] font-bold leading-snug" style={{ color: BRAND.navy }}>
                        {step.title}
                      </span>
                      <span className="mt-0.5 block text-[10px] leading-snug" style={{ color: 'rgba(26,26,26,0.62)' }}>
                        {step.blurb}
                      </span>
                    </span>
                    <ArrowRight
                      className="mt-[3px] h-3 w-3 shrink-0 transition-transform group-hover:translate-x-0.5"
                      style={{ color: BRAND.copper }}
                    />
                  </Link>
                ))}
              </div>
            )}
          </div>
        </>
      )}
    </section>
  );
}